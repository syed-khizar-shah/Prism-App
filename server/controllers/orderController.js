// Create a new order
const createOrder = async (req, res) => {
  try {
    const {
      customer,
      selections,
      promo,
      payment,
      notes,
      salesperson,
      storeLocation,
      status
    } = req.body;

    console.log({
      customer,
      selections,
      promo,
      payment,
      notes,
      salesperson,
      storeLocation,
      status
    })

    // Validate required fields
    if (!customer || !customer.name) {
      return res.status(400).json({
        success: false,
        error: 'Customer name is required'
      });
    }

    if (!selections || selections.length === 0) {
      return res.status(400).json({
        success: false,
        error: 'At least one selection is required'
      });
    }

    if (!payment || !payment.method || !payment.amount) {
      return res.status(400).json({
        success: false,
        error: 'Payment method and amount are required'
      });
    }

    // Calculate pricing from selections
    const subtotal = selections.reduce((total, selection) => {
      return total + (selection.selectionPrice || 0);
    }, 0);

    const discount = promo ? (promo.appliedDiscount || 0) : 0;
    const totalPrice = subtotal - discount;

    // Create the order
    const order = new Order({
      customer,
      selections,
      promo,
      payment,
      pricing: {
        subtotal,
        discount,
        totalPrice,
        tax: 0,
        shipping: 0
      },
      notes,
      salesperson,
      storeLocation,
      status
    });

    // Order ID will be automatically generated by the schema pre-save middleware

    // Save the order
    const savedOrder = await order.save();
    console.log({ savedOrder })

    res.status(201).json({
      success: true,
      order: savedOrder,
      message: 'Order created successfully'
    });

  } catch (error) {
    console.error('Error creating order:', error);

    // Provide more detailed error information
    let errorMessage = 'Failed to create order';
    if (error.name === 'ValidationError') {
      errorMessage = 'Validation error: ' + Object.values(error.errors).map(err => err.message).join(', ');
    } else if (error.code === 11000) {
      errorMessage = 'Duplicate order ID';
    }

    res.status(500).json({
      success: false,
      error: errorMessage,
      details: error.message
    });
  }
};

// Get all orders with pagination and filtering
const getOrders = async (req, res) => {
  try {
    const {
      page = 1,
      limit = 10,
      status,
      customerName,
      startDate,
      endDate,
      sortBy = 'orderDate',
      sortOrder = 'desc'
    } = req.query;

    // Build filter object
    const filter = {};

    if (status) {
      filter.status = status;
    }

    if (customerName) {
      filter['customer.name'] = { $regex: customerName, $options: 'i' };
    }

    if (startDate || endDate) {
      filter.orderDate = {};
      if (startDate) filter.orderDate.$gte = new Date(startDate);
      if (endDate) filter.orderDate.$lte = new Date(endDate);
    }

    // Build sort object
    const sort = {};
    sort[sortBy] = sortOrder === 'desc' ? -1 : 1;

    // Calculate skip value for pagination
    const skip = (parseInt(page) - 1) * parseInt(limit);

    // Execute query
    const orders = await Order.find(filter)
      .sort(sort)
      .skip(skip)
      .limit(parseInt(limit));

    // Get total count for pagination
    const total = await Order.countDocuments(filter);

    res.json({
      success: true,
      orders,
      total,
      page: parseInt(page),
      limit: parseInt(limit),
      totalPages: Math.ceil(total / parseInt(limit))
    });

  } catch (error) {
    console.error('Error fetching orders:', error);
    res.status(500).json({
      success: false,
      error: 'Failed to fetch orders',
      details: error.message
    });
  }
};

